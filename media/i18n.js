  /**
   * @param {string} setting 'auto' | 'zh-CN' | 'en'
   * @param {string | undefined} uiLanguage Kiro's display language, e.g. 'zh-cn'
   * @returns {'zh' | 'en'}
   */
  function resolveLang(setting, uiLanguage) {
    if (setting === 'en') return 'en';
    if (setting === 'zh-CN') return 'zh';
    return String(uiLanguage || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
  }

  /**
   * @param {string} lang
   * @param {string} key
   * @param {Record<string, unknown>} [params]
   */
  function t(lang, key, params) {
    const table = messages[lang === 'en' ? 'en' : 'zh'];
    const s = table[key] ?? messages.zh[key] ?? key;
    return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
  }

